// Downloads the 24 spell symbols of the Atari ST version (7 × 7 pixels each) from the
// Dungeon Master Encyclopaedia and writes them as masks into src/core/spell-glyphs.js
// (docs/029 § G1, docs/030). Run once: node tools/fetch-spell-glyphs.mjs

import { writeFileSync } from 'node:fs';
import { inflateSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { SYMBOLS } from '../src/core/spell-info.js';

const URL_OF = (name) => `http://dmweb.free.fr/files/Game,Dungeon_Master,Atari_ST,Symbol,${name},Screenshot.png`;
const OUT = new URL('../src/core/spell-glyphs.js', import.meta.url);

// Minimal PNG decoder: 8-bit RGBA or RGB, not interlaced (what the Encyclopaedia serves).
function decodePng(buffer) {
  let offset = 8;
  let width, height, colorType;
  const data = [];
  while (offset < buffer.length) {
    const length = buffer.readUInt32BE(offset);
    const type = buffer.toString('ascii', offset + 4, offset + 8);
    const chunk = buffer.subarray(offset + 8, offset + 8 + length);
    if (type === 'IHDR') {
      width = chunk.readUInt32BE(0);
      height = chunk.readUInt32BE(4);
      if (chunk[8] !== 8 || chunk[12] !== 0) throw new Error('PNG non géré (profondeur ou entrelacement)');
      colorType = chunk[9];
    } else if (type === 'IDAT') data.push(chunk);
    offset += 12 + length;
  }
  const channels = { 2: 3, 6: 4 }[colorType];
  if (!channels) throw new Error(`PNG non géré (type de couleur ${colorType})`);
  const raw = inflateSync(Buffer.concat(data));
  const stride = width * channels;
  const pixels = Buffer.alloc(stride * height);
  for (let y = 0; y < height; y++) {
    const filter = raw[y * (stride + 1)];
    for (let i = 0; i < stride; i++) {
      const x = raw[y * (stride + 1) + 1 + i];
      const a = i >= channels ? pixels[y * stride + i - channels] : 0;
      const b = y ? pixels[(y - 1) * stride + i] : 0;
      const c = y && i >= channels ? pixels[(y - 1) * stride + i - channels] : 0;
      const p = a + b - c;
      const paeth = Math.abs(p - a) <= Math.abs(p - b) && Math.abs(p - a) <= Math.abs(p - c) ? a : Math.abs(p - b) <= Math.abs(p - c) ? b : c;
      const predictor = [0, a, b, (a + b) >> 1, paeth][filter];
      pixels[y * stride + i] = (x + predictor) & 0xff;
    }
  }
  return { width, height, channels, pixels };
}

// A pixel is part of the symbol when it is opaque and brighter than the background.
function maskOf({ width, height, channels, pixels }) {
  const rows = [];
  for (let y = 0; y < height; y++) {
    let row = '';
    for (let x = 0; x < width; x++) {
      const p = (y * width + x) * channels;
      const alpha = channels === 4 ? pixels[p + 3] : 255;
      row += alpha > 127 && pixels[p] + pixels[p + 1] + pixels[p + 2] > 384 ? '#' : '.';
    }
    rows.push(row);
  }
  return rows;
}

const glyphs = {};
for (const name of SYMBOLS.flat()) {
  const response = await fetch(URL_OF(name));
  if (!response.ok) throw new Error(`${name} : HTTP ${response.status}`);
  glyphs[name] = maskOf(decodePng(Buffer.from(await response.arrayBuffer())));
  console.log(name.padEnd(5), glyphs[name].join(' '));
}

const body = Object.entries(glyphs)
  .map(([name, rows]) => `  ${name}: [${rows.map((r) => `'${r}'`).join(', ')}],`)
  .join('\n');
writeFileSync(
  OUT,
  `// The 24 spell symbols of the Atari ST version, 7 × 7 pixels ('#' = ink), generated by
// tools/fetch-spell-glyphs.mjs from the Dungeon Master Encyclopaedia
// (http://dmweb.free.fr/files/Game,Dungeon_Master,Atari_ST,Symbol,<Name>,Screenshot.png).

// prettier-ignore
export const GLYPHS = {
${body}
};
`,
);
console.log(`→ ${fileURLToPath(OUT)}`);
